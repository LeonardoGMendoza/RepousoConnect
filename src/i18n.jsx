export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    try {
      const saved = localStorage.getItem('masperto-language');
      if (saved && translations[saved]) return saved;
    } catch { /* localStorage indisponível */ }
    try {
      const nav = (navigator.language || 'pt').slice(0, 2).toLowerCase();
      if (translations[nav]) return nav;
    } catch { /* ignore */ }
    return 'pt';
  });

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = RTL_LANGS.has(language) ? 'rtl' : 'ltr';
    try { localStorage.setItem('masperto-language', language); } catch { /* ignore */ }
  }, [language]);

  const setLanguage = useCallback((code) => {
    if (translations[code]) setLanguageState(code);
  }, []);

  const t = useCallback((key, params) => {
    const dict = translations[language] || translations.pt;
    let str = dict[key] ?? translations.pt[key] ?? key;
    if (params) {
      Object.keys(params).forEach((p) => {
        str = str.split(`{${p}}`).join(String(params[p]));
      });
    }
    return str;
  }, [language]);

  const dir = RTL_LANGS.has(language) ? 'rtl' : 'ltr';

  const value = { language, setLanguage, t, dir, languages: LANGUAGES };

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

// ── Hook ─────────────────────────────────────────────────────────────────
export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage deve ser usado dentro de LanguageProvider');
  return ctx;
}

// ── Componente pronto: seletor de idioma (dropdown) ────────────────────────
export function LanguageSelector({ style }) {
  const { language, setLanguage, languages } = useLanguage();
  return (
    <select
      value={language}
      onChange={(e) => setLanguage(e.target.value)}
      className="language-selector"
      style={style}
    >
      {languages.map((l) => (
        <option key={l.code} value={l.code}>{l.name}</option>
      ))}
    </select>
  );
}

